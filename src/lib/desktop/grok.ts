import { invoke, isTauri } from "@tauri-apps/api/core";
import { hasExactKeys, isObject } from "./providers";
import {
    APPLY_ERROR_CODES,
    PLAN_ERROR_CODES,
    ApplyRequestError,
    PlanRequestError,
    appliedResult,
    change,
    notice,
    planSource,
    targetFile,
    type ClaudeCodeApplied,
    type ConfigChange,
    type PlanNotice,
    type PlanSource,
    type PlanTargetFile,
} from "./agents";

/** Files that can outrank the settings file; listed by name, never read here. */
export const GROK_PRECEDENCE_FILES = [
    "managed_config.toml",
    "requirements.toml",
] as const;
export type GrokPrecedenceName = (typeof GROK_PRECEDENCE_FILES)[number];
/** Existence of a higher layer; content is never read by the preview. */
export const GROK_LAYER_STATES = ["absent", "present", "unavailable"] as const;
export type GrokLayerState = (typeof GROK_LAYER_STATES)[number];

export interface GrokPrecedenceFile {
    name: GrokPrecedenceName;
    state: GrokLayerState;
}

/** Fields this adapter writes; anything else in the reply is rejected. */
const ALIAS_FIELDS = [
    "model",
    "base_url",
    "name",
    "api_backend",
    "api_key",
    "context_window",
    "vision",
] as const;

/** A readable `[model.<alias>]` name generated by the adapter. */
const ALIAS_PATTERN = /^vibemate-[a-z0-9][a-z0-9_-]{0,158}$/u;

/** Source and treatment of context capacity, not a per-request output limit. */
export interface GrokContextWindow {
    source: "library" | "notStated";
    state: "written" | "unchanged" | "notStated";
    value: string | null;
}

/** Grok's model-local image declaration and its origin/write state. */
export interface GrokImageInput {
    source: "catalog" | "userDeclaration" | "notStated";
    state: "written" | "unchanged" | "notStated";
    value: boolean | null;
}

/** Grok Build model preview: one file, its changes and the layers above it. */
export interface GrokPlan {
    agent: "grokBuild";
    modelAlias: string;
    existingAlias: boolean;
    contextWindow: GrokContextWindow;
    imageInput: GrokImageInput;
    file: { target: PlanTargetFile; changes: ConfigChange[] };
    precedence: GrokPrecedenceFile[];
    notices: PlanNotice[];
    source: PlanSource;
    restartRequired: boolean;
}

function invalid(): never {
    throw new PlanRequestError("invalid_response");
}

/**
 * Strictly parse the Grok preview.
 *
 * The reply is treated as untrusted data: keys must match exactly, the alias must
 * carry the adapter's own shape, every changed key must be one this adapter owns,
 * and the planned credential must stay masked. A response that fails is refused
 * before it can be displayed or approved.
 */
function parsePlan(
    value: unknown,
    providerId: string,
    modelId: string,
): GrokPlan {
    if (
        !isObject(value) ||
        !hasExactKeys(value, [
            "agent",
            "modelAlias",
            "existingAlias",
            "contextWindow",
            "imageInput",
            "file",
            "precedence",
            "notices",
            "source",
            "restartRequired",
        ]) ||
        value["agent"] !== "grokBuild" ||
        // Grok reads configuration when a session starts, so a written plan
        // always needs a new session; a reply claiming otherwise is not this contract.
        value["restartRequired"] !== true ||
        typeof value["modelAlias"] !== "string" ||
        !ALIAS_PATTERN.test(value["modelAlias"]) ||
        typeof value["existingAlias"] !== "boolean" ||
        !Array.isArray(value["notices"])
    )
        return invalid();
    const modelAlias = value["modelAlias"];
    const notices = value["notices"].map(notice);
    const file = value["file"];
    if (
        !isObject(file) ||
        !hasExactKeys(file, ["target", "changes"]) ||
        !Array.isArray(file["changes"]) ||
        file["changes"].length === 0 ||
        file["changes"].length > ALIAS_FIELDS.length
    )
        return invalid();
    const changes = file["changes"].map(change);
    if (new Set(changes.map((entry) => entry.keyPath)).size !== changes.length)
        return invalid();
    const target = targetFile(file["target"]);
    // Rust names the settings file below the Agent root; accept either native
    // separator because the path comes from the desktop platform, not from here.
    if (!/[\\/]config\.toml$/u.test(target.path)) return invalid();
    const prefix = `model.${modelAlias}.`;
    const allowed = new Set<string>(
        ALIAS_FIELDS.map((field) => `${prefix}${field}`),
    );
    if (changes.some((entry) => !allowed.has(entry.keyPath))) return invalid();
    const planned = (keyPath: string): ConfigChange | undefined =>
        changes.find((entry) => entry.keyPath === keyPath);
    const key = planned(`${prefix}api_key`);
    if (
        // The credential position is mandatory and masked on both sides, so a
        // real key can never travel through the plan.
        key === undefined ||
        !key.secret ||
        (key.before !== null && key.before !== "••••••••") ||
        changes.filter((entry) => entry.secret).length !== 1 ||
        planned(`${prefix}model`)?.after !== modelId ||
        changes.some(
            (entry) => entry.secret !== (entry.keyPath === `${prefix}api_key`),
        )
    )
        return invalid();
    const context = value["contextWindow"];
    if (
        !isObject(context) ||
        !hasExactKeys(context, ["source", "state", "value"]) ||
        (context["source"] !== "library" &&
            context["source"] !== "notStated") ||
        (context["state"] !== "written" &&
            context["state"] !== "unchanged" &&
            context["state"] !== "notStated") ||
        (context["value"] !== null &&
            (typeof context["value"] !== "string" ||
                !/^-?(?:0|[1-9]\d{0,18})$/u.test(context["value"])))
    )
        return invalid();
    const contextWindow: GrokContextWindow = {
        source: context["source"],
        state: context["state"],
        value: context["value"],
    };
    const contextChange = planned(`${prefix}context_window`);
    // A summary must agree with the write, not just have valid enum spellings.
    if (
        (contextWindow.state === "written") !==
            (contextWindow.source === "library") ||
        (contextWindow.state === "written") !== (contextChange !== undefined) ||
        (contextWindow.state === "written" &&
            (contextWindow.value === null ||
                !/^[1-9]\d*$/u.test(contextWindow.value) ||
                contextChange?.after !== contextWindow.value)) ||
        (contextWindow.state === "notStated" && contextWindow.value !== null) ||
        (contextWindow.state === "unchanged" && !value["existingAlias"])
    )
        return invalid();
    const image = value["imageInput"];
    if (
        !isObject(image) ||
        !hasExactKeys(image, ["source", "state", "value"]) ||
        (image["source"] !== "catalog" &&
            image["source"] !== "userDeclaration" &&
            image["source"] !== "notStated") ||
        (image["state"] !== "written" &&
            image["state"] !== "unchanged" &&
            image["state"] !== "notStated") ||
        (image["value"] !== null && typeof image["value"] !== "boolean")
    )
        return invalid();
    const imageInput: GrokImageInput = {
        source: image["source"],
        state: image["state"],
        value: image["value"],
    };
    const imageChange = planned(`${prefix}vision`);
    if (
        (imageInput.state === "written") !== (imageChange !== undefined) ||
        (imageInput.state === "written" &&
            (imageInput.source === "notStated" ||
                imageInput.value === null ||
                imageChange?.after !== String(imageInput.value))) ||
        (imageInput.state === "unchanged" &&
            (!value["existingAlias"] || imageInput.source !== "notStated")) ||
        (imageInput.state === "notStated" &&
            (imageInput.source !== "notStated" || imageInput.value !== null))
    )
        return invalid();
    const precedence = value["precedence"];
    if (!Array.isArray(precedence) || precedence.length !== 2) return invalid();
    const layers = precedence.map((entry: unknown): GrokPrecedenceFile => {
        if (
            !isObject(entry) ||
            !hasExactKeys(entry, ["name", "state"]) ||
            typeof entry["name"] !== "string"
        )
            return invalid();
        const name = GROK_PRECEDENCE_FILES.find(
            (known) => known === entry["name"],
        );
        const state = GROK_LAYER_STATES.find(
            (known) => known === entry["state"],
        );
        if (name === undefined || state === undefined) return invalid();
        return { name, state };
    });
    const source = planSource(value["source"]);
    if (
        // Each layer is listed once, and the identity must be the one asked for.
        new Set(layers.map((layer) => layer.name)).size !== layers.length ||
        source.providerId !== providerId ||
        source.modelId !== modelId
    )
        return invalid();
    return {
        agent: "grokBuild",
        modelAlias,
        existingAlias: value["existingAlias"],
        contextWindow,
        imageInput,
        file: { target, changes },
        precedence: layers,
        notices,
        source,
        restartRequired: true,
    };
}

/** Preview `config.toml` without credentials or writes; browser mode invents no plan. */
export async function planGrokSettings(
    providerId: string,
    modelId: string,
    entryPath: string | null,
): Promise<{ kind: "preview" } | { kind: "desktop"; plan: GrokPlan }> {
    if (!isTauri()) return { kind: "preview" };
    let value: unknown;
    try {
        value = await invoke<unknown>("plan_grok_settings", {
            providerId,
            modelId,
            entryPath,
        });
    } catch (error: unknown) {
        throw new PlanRequestError(
            PLAN_ERROR_CODES.find((code) => code === error) ??
                "operation_failed",
        );
    }
    const plan = parsePlan(value, providerId, modelId);
    return { kind: "desktop", plan };
}

/**
 * The tokens that alone can approve a Grok write.
 *
 * Only the reviewed identity and change tokens travel back; the path is compared
 * by Rust, never taken as a target to write.
 */
export interface ReviewedGrokPlan {
    modelAlias: string;
    file: { path: string; contentDigest: string | null };
    providerRevision: number;
    modelContentDigest: string;
}

/** Extract every token one Grok preview showed. */
export function reviewedGrokPlan(plan: GrokPlan): ReviewedGrokPlan {
    return {
        modelAlias: plan.modelAlias,
        file: {
            path: plan.file.target.path,
            contentDigest: plan.file.target.contentDigest,
        },
        providerRevision: plan.source.providerRevision,
        modelContentDigest: plan.source.modelContentDigest,
    };
}

/**
 * Apply the reviewed plan and check the acknowledgment.
 *
 * One file means one step, so the answer is refused unless it describes exactly
 * that file: a restart hint without a written key, an `applied` state with no
 * step, or a `failed` state that claims a file changed would all be reported as
 * `invalid_response` instead of reaching the user as success.
 */
export async function applyGrokSettings(
    providerId: string,
    modelId: string,
    entryPath: string | null,
    reviewed: ReviewedGrokPlan,
): Promise<ClaudeCodeApplied> {
    if (!isTauri()) throw new ApplyRequestError("desktop_required");
    let value: unknown;
    try {
        value = await invoke<unknown>("apply_grok_settings", {
            input: { providerId, modelId, entryPath, reviewed },
        });
    } catch (error: unknown) {
        throw new ApplyRequestError(
            APPLY_ERROR_CODES.find((code) => code === error) ??
                "operation_failed",
        );
    }
    const result = appliedResult(value);
    if (
        result.steps.length > 1 ||
        result.steps.some((step) => step.targetPath !== reviewed.file.path) ||
        (result.state === "applied" && result.steps.length !== 1) ||
        (result.state === "failed" &&
            result.steps.some((step) => step.state !== "failed")) ||
        result.restartRequired !== (result.state === "applied")
    )
        throw new ApplyRequestError("invalid_response");
    return result;
}
